-- =========================================================================
-- BIX - Product Backlog & Sprint Workflow schema
-- Journey 3 / US-06, US-08a, US-08b, US-10
-- =========================================================================
-- Raw PostgreSQL DDL. This project has no migration framework, so these
-- scripts are run by hand (see server/db/README.md).
--
-- Re-run safety: every statement uses CREATE ... IF NOT EXISTS or
-- CREATE OR REPLACE, and nothing here drops a table or deletes data.
-- Re-running this file will NOT alter a table that already exists - to
-- change a column or constraint after the fact, write a separate migration
-- script; do not edit this file and expect a re-run to apply the change.
--
-- Requires PostgreSQL 12 or newer (developed against 14+). Uses identity
-- columns, a multi-column foreign key, and one PL/pgSQL trigger.
-- =========================================================================

BEGIN;

-- -------------------------------------------------------------------------
-- projects
--   Top of the hierarchy. A project may have zero sprints and zero PBIs.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS projects (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text   NOT NULL
);

-- -------------------------------------------------------------------------
-- sprints
--   Each sprint belongs to exactly one project. A sprint may have zero PBIs.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sprints (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint      NOT NULL
                           REFERENCES projects (id) ON DELETE RESTRICT,
    name       text        NOT NULL,
    status     text        NOT NULL DEFAULT 'planning'
                           CHECK (status IN ('planning', 'active', 'completed')),
    started_at timestamptz,                    -- NULL until the sprint is started (US-10)
    created_at timestamptz NOT NULL DEFAULT now(),

    -- Target for the composite foreign key on product_backlog_items that
    -- enforces "a PBI's sprint is in the PBI's project". Uniqueness is
    -- already guaranteed by the primary key on id; PostgreSQL still requires
    -- an explicit unique constraint on the exact referenced column list.
    CONSTRAINT sprints_id_project_key UNIQUE (id, project_id)
);

CREATE INDEX IF NOT EXISTS idx_sprints_project_id ON sprints (project_id);

-- -------------------------------------------------------------------------
-- product_backlog_items  (PBIs)
--   Belongs to exactly one project. Optionally belongs to one sprint
--   (sprint_id is NULL while the PBI sits in the Product Backlog). When a
--   sprint is set it must belong to the same project as the PBI.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_backlog_items (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint       NOT NULL
                                    REFERENCES projects (id) ON DELETE RESTRICT,
    sprint_id          bigint,      -- nullable: unset while in the Product Backlog
    title              text         NOT NULL,
    description        text,
    stage              text         NOT NULL DEFAULT 'product_backlog'
                                    CHECK (stage IN ('product_backlog',
                                                     'sprint_planning',
                                                     'active_sprint',
                                                     'completed')),
    planned_start_date date,
    planned_end_date   date,
    estimated_hours    numeric(6,2) CHECK (estimated_hours >= 0),
    actual_hours       numeric(6,2) CHECK (actual_hours   >= 0),
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),

    -- planned_end_date must not fall before planned_start_date.
    -- Passes when either date is still NULL (range not fully entered yet).
    CONSTRAINT pbi_planned_dates_order_chk
        CHECK (planned_start_date IS NULL
               OR planned_end_date IS NULL
               OR planned_end_date >= planned_start_date),

    -- Same-project rule for the optional sprint link. This multi-column
    -- foreign key uses the default MATCH SIMPLE behaviour: when sprint_id
    -- IS NULL the constraint is not checked at all (correct for Product
    -- Backlog items); when sprint_id IS NOT NULL the pair (sprint_id,
    -- project_id) must exist in sprints, which also proves the sprint's
    -- project matches the PBI's project.
    CONSTRAINT pbi_sprint_same_project_fkey
        FOREIGN KEY (sprint_id, project_id)
        REFERENCES sprints (id, project_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_pbi_project_id       ON product_backlog_items (project_id);
CREATE INDEX IF NOT EXISTS idx_pbi_sprint_id        ON product_backlog_items (sprint_id);
CREATE INDEX IF NOT EXISTS idx_pbi_project_id_stage ON product_backlog_items (project_id, stage);

-- -------------------------------------------------------------------------
-- tasks
--   Each task belongs to exactly one PBI. A PBI may have zero tasks.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tasks (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pbi_id bigint NOT NULL
                  REFERENCES product_backlog_items (id) ON DELETE RESTRICT,
    title  text   NOT NULL,
    -- FLAG: the allowed set of status values, whether the column is NOT NULL,
    -- and any default were NOT specified for tasks. Left as free text with no
    -- CHECK and no default, pending a team decision. See server/db/README.md
    -- ("Open questions and flags"). Add a CHECK (...) via migration once the
    -- vocabulary is agreed.
    status text
);

CREATE INDEX IF NOT EXISTS idx_tasks_pbi_id ON tasks (pbi_id);

-- -------------------------------------------------------------------------
-- sub_tasks
--   Each sub-task belongs to exactly one task. A task may have zero sub-tasks.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sub_tasks (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL
                   REFERENCES tasks (id) ON DELETE RESTRICT,
    title   text   NOT NULL,
    -- FLAG: same as tasks.status - allowed values / nullability / default are
    -- a pending team decision. See server/db/README.md.
    status  text
);

CREATE INDEX IF NOT EXISTS idx_sub_tasks_task_id ON sub_tasks (task_id);

-- -------------------------------------------------------------------------
-- updated_at maintenance
--   product_backlog_items.updated_at is bumped to now() on every UPDATE by
--   this trigger, so application code cannot forget to set it. created_at is
--   never touched. No other table in this schema has an updated_at column,
--   so only one trigger is installed.
-- -------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pbi_set_updated_at ON product_backlog_items;
CREATE TRIGGER trg_pbi_set_updated_at
    BEFORE UPDATE ON product_backlog_items
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

-- =========================================================================
-- Users, teams and membership
-- -------------------------------------------------------------------------
-- Resolves part of "PENDING: user assignment columns" below: the users
-- table did not exist anywhere in the repo (server/db/README.md ->
-- "Pending integration with login / users" flagged this). Its shape matches
-- exactly what server/src/models/userModel.js already queries
-- (SELECT * FROM users WHERE email = $1) and the DEMO_USERS fallback shape
-- in that same file (id, name, email, role, password_hash) - no new
-- contract, just the table that was always implied.
--
-- Team membership (team_members) and project membership (project_members)
-- are modeled as two independent tables, not a Developer -> Team -> Project
-- hierarchy: README.md's own pending-decisions list named a "project_members
-- / role table" as an open question, and US-05 requires a developer to be
-- *explicitly* assigned to a project, not merely on a team that happens to
-- own it (no such "team owns project" link exists here, and none is added).
-- Nothing above this line (projects, sprints, product_backlog_items, tasks,
-- sub_tasks) is modified.
-- =========================================================================

-- -------------------------------------------------------------------------
-- users
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL,
    email         text        NOT NULL,
    role          text        NOT NULL CHECK (role IN ('admin', 'developer')),
    password_hash text        NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

-- -------------------------------------------------------------------------
-- teams
--   A developer team, independent of any one project - an admin can staff a
--   team before it has any project work. See the note above on why project
--   membership is not derived from this.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS teams (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT teams_name_key UNIQUE (name)
);

-- -------------------------------------------------------------------------
-- team_members
--   Which users are on which team. The composite primary key doubles as the
--   uniqueness constraint (a user can't be added to the same team twice).
--
--   Deletes CASCADE here, unlike the ON DELETE RESTRICT used everywhere
--   above: a membership row is a pure link with no content of its own, so
--   once its team or user is gone the membership row should simply go with
--   it rather than block that delete. This is a deliberate, narrow
--   exception to the "Deletion behaviour" policy in server/db/README.md,
--   which is about protecting real work data (sprints/PBIs/tasks), not
--   membership rows.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS team_members (
    team_id    bigint      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    user_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (team_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_team_members_user_id ON team_members (user_id);

-- -------------------------------------------------------------------------
-- project_members
--   Which users may access which project. This is what US-05 ("a developer
--   can view/access only project boards they are explicitly assigned to")
--   is checked against - see server/src/models/projectMembershipModel.js.
--   Same CASCADE reasoning as team_members above.
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_members (
    project_id bigint      NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (project_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_project_members_user_id ON project_members (user_id);

COMMIT;

